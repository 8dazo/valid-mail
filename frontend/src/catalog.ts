export type Category =
  "Validation" | "Conversion" | "Generators" | "Developer" | "Text";
export type Field = {
  key: string;
  label: string;
  type?: "text" | "textarea" | "select" | "number" | "password";
  helper?: string;
  when?: [string, string];
  placeholder?: string;
  defaultValue?: string;
  options?: [string, string][];
};
export type Tool = {
  id: string;
  name: string;
  description: string;
  category: Category;
  icon: string;
  color: string;
  action: string;
  fields: Field[];
  example: Record<string, string>;
  source?: string;
  library: string;
  note?: string;
  featured?: boolean;
  server?: boolean;
  engine?: "go";
  layout?: "document" | "code" | "compare" | "compact" | "generator";
};
const text = (label = "Input", key = "input", placeholder = ""): Field => ({
  key,
  label,
  type: "textarea",
  placeholder,
});
const select = (
  key: string,
  label: string,
  options: [string, string][],
  defaultValue?: string,
): Field => ({
  key,
  label,
  type: "select",
  options,
  defaultValue: defaultValue ?? options[0][0],
});
